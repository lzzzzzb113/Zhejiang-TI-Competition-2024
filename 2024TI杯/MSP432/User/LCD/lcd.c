/******************************************************************************
      函数说明：画线
      入口数据：x1,y1   起始坐标
                x2,y2   终止坐标
                color   线的颜色
      返回值：  无
******************************************************************************/
void LCD_DrawLine(u16 x1,u16 y1,u16 x2,u16 y2,u16 color)
{
	u16 t; 
	int xerr=0,yerr=0,delta_x,delta_y,distance;
	int incx,incy,uRow,uCol;
	delta_x=x2-x1; //计算坐标增量 
	delta_y=y2-y1;
	uRow=x1;//画线起点坐标
	uCol=y1;
	if(delta_x>0)incx=1; //设置单步方向 
	else if (delta_x==0)incx=0;//垂直线 
	else {incx=-1;delta_x=-delta_x;}
	if(delta_y>0)incy=1;
	else if (delta_y==0)incy=0;//水平线 
	else {incy=-1;delta_y=-delta_y;}
	if(delta_x>delta_y)distance=delta_x; //选取基本增量坐标轴 
	else distance=delta_y;
	for(t=0;t<distance+1;t++)
	{
		#if USE_FRAMEBUFFER
		/* 将划过的线,置2 */
		FrameBuffer[uCol][uRow] += 2;
		#endif /* USE_FRAMEBUFFER */
		LCD_DrawPoint(uRow,uCol,color);//画点
		xerr+=delta_x;
		yerr+=delta_y;
		if(xerr>distance)
		{
			xerr-=distance;
			uRow+=incx;
		}
		if(yerr>distance)
		{
			yerr-=distance;
			uCol+=incy;
		}
	}
}

uint8_t sendadcbuff[129];

float JiBoVal;
float XieBoVal,XieBoVal3,XieBoVal4,XieBoVal5;
char texta[30];
extern uint16_t THDx;
/**
 * @brief: 传入数据，在显示屏上画波形
 * @param  y 为要画的一组数据的地址
 * @param  NumToDraw 要画的数据的个数
 * @return None
 * @note:  修改keil优化等级可以有效的提升屏幕帧率
 * @Sample Draw_Wave(usWaveBuf, sizeof(usWaveBuf)/sizeof(usWaveBuf[0]));
 */
void Draw_Wave(uint32_t* y, uint16_t NumToDraw)
{
	static signed char	FindIndex = 4;
	unsigned char buffvalue;
	static uint16_t LastChangeDispCnt;
	uint16_t Num,ChangeDispCnt=0;
	float CurrentValue = 0, LastValue = 0;
	float ymax = y[0]; 
	float ymin = y[0]; 
	
	/* 若传入的参数大于屏幕量程 */
	if(NumToDraw>WaveGrid_MAX_X_SIZE)
	{
		/* 修改采样率 */
		FindIndex ++;
		if(FindIndex > 4)	FindIndex = 4;
		NumToDraw = WaveGrid_MAX_X_SIZE;
	}
	if(NumToDraw<39)
	{
		FindIndex --;
		if(FindIndex <= 0) FindIndex = 0;
//		ChangeSampFreq = 1;
//		sampfreq = samp_freqtab[FindIndex];
	}
	
	/* 先打印数据，否则要延迟好久 */
	LCD_Fill(0,98,128,128,WHITE);
	sprintf(texta,"THD=%02d.%d%%",THDx/10,THDx%10); 	//显示输入信号失真度THDx值
	LCD_ShowString(40, 98, (const u8 *)texta,BLACK, WHITE, 12, 1);
	
	sprintf(texta,"JiBo=%.2f",JiBoVal); 	//显示输入信号失真度THDx值
	LCD_ShowString(40, 110, (const u8 *)texta,BLACK, WHITE, 12, 1);
	
	LCD_Fill(0,0,128,24,WHITE);
	sprintf(texta,"2Xie=%.2f",XieBoVal); 	//显示输入信号失真度THDx值
	LCD_ShowString(0, 0, (const u8 *)texta,BLACK, WHITE, 12, 1);
	
	sprintf(texta,"3Xie=%.2f",XieBoVal3); 	//显示输入信号失真度THDx值
	LCD_ShowString(60, 0, (const u8 *)texta,BLACK, WHITE, 12, 1);
	
	sprintf(texta,"4Xie=%.2f",XieBoVal4); 	//显示输入信号失真度THDx值
	LCD_ShowString(0, 12, (const u8 *)texta,BLACK, WHITE, 12, 1);
	
	sprintf(texta,"5Xie=%.2f",XieBoVal5); 	//显示输入信号失真度THDx值
	LCD_ShowString(60, 12, (const u8 *)texta,BLACK, WHITE, 12, 1);
	
	/* 找到输入数据的最大值与最小值 */
	for(Num=1;Num<NumToDraw;Num++)
	{
		if (y[Num] > ymax)
		{
			ymax = y[Num];
		} 
		else if (y[Num] < ymin)
		{
			ymin = y[Num];
		}
	}
	
	/* 根据输入的多少个数据画线 */
	for(Num=0;Num<NumToDraw;Num++)
	{
		/* 保存上一次y轴数据，画线用 */
		LastValue = CurrentValue; 
		
		/* 如果输入的数据小于x轴像素，把数据归到0-239(缩放x轴) */
		if(NumToDraw < WaveGrid_MAX_X_SIZE)
		{
			float CaluNewX;
			CaluNewX = (float) Num / NumToDraw * WaveGrid_MAX_X_SIZE;
			ChangeDispCnt = CaluNewX;
		}
		else
		{
			ChangeDispCnt ++;
		}
		
		/* 利用归一化把数据归一到0-180（与屏幕y轴像素相同） */
		CurrentValue = (float)(y[Num] - ymin) / (ymax - ymin) * 60;
		
		/* 发送数据到上位机显示波形 */
		buffvalue = (uint8_t)CurrentValue;
		sendadcbuff[Num] = buffvalue;
		
		/* 如果是第一次画点或切屏，则无需连线，直接清屏描点即可 */
		if( ( Num % WaveGrid_MAX_X_SIZE ) == 0 )
		{
			/* 画网格（网格大小240*180），同时清除画过的线 */
			DrawGrid(WaveGrid_X_START_POS,WaveGrid_Y_START_POS,\
							 WaveGrid_X_END_POS ,WaveGrid_Y_END_POS);
			
			/* 画第一个点 */
			LCD_DrawPoint(WaveGrid_X_START_POS + 0,WaveGrid_MAX_Y_SIZE - CurrentValue,RED);
			
			ChangeDispCnt = 0;
		}
		else
		{
			/* 画线 */
			LCD_DrawLine(WaveGrid_X_START_POS + LastChangeDispCnt, WaveGrid_MAX_Y_SIZE - LastValue, 
									 WaveGrid_X_START_POS + ChangeDispCnt    , WaveGrid_MAX_Y_SIZE - CurrentValue,RED);
		}
		
		/* 保存上一次x轴数据，画线用 */
		LastChangeDispCnt = ChangeDispCnt;
	}
}

