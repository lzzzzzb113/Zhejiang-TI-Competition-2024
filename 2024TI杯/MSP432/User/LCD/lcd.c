/**
	*@Brief 画网格(Size=xsize*ysize)
	*@Param xstart x起始位置
	*@Param ystart y起始位置
	*@Param xEnd 	 x结束位置
	*@Param yEnd   y结束位置
	*/
static void DrawGrid(uint8_t xstart,uint8_t ystart,uint8_t xEnd,uint8_t yEnd)
{
	/* 画列点 */
	u16 index_x,index_y;
	
	/* 清屏.白色背景 */
	LCD_Fill(0,0,128,128,WHITE);
	
	/* 从x=xstart开始，每列间隔20个像素 */ 
	for (index_x = xstart; index_x <= xEnd; index_x += 16)
	{
		/* 从y=0开始，各各列的每个点间隔4个像素 */
		for (index_y = ystart; index_y <= yEnd; index_y += 4)
		{
				LCD_DrawPoint(index_x, index_y, GRAY);
		}
	}
	/* 画行点 */
	/* 从y=ystart开始，每行间隔15个像素 */
	for (index_y =ystart; index_y <= yEnd; index_y += 16)
	{
		/* 从x=xstar开始，各各行的每个点间隔4个像素 */
		for (index_x = xstart; index_x < xEnd; index_x += 4)
		{
			LCD_DrawPoint(index_x, index_y, GRAY);
		}
	}
}

